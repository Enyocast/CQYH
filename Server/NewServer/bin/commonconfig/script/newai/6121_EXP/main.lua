local g_oGameWorld = CGameWorld:GetInstance();

function add_exp(owner)
	local ai = owner:GetAIProcessor();
	local role = g_oGameWorld:FindValidRole(ai:GetTargetID());
	if role then
		local exp = EXP_TABLE[role:GetLevel()];
		role:AddExp(exp, false, true);
		return brvSuccess;
	end

	return brvFail;
end

