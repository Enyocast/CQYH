	local targetLevel = math.random(20,45);
	--local targetLevel = 12;
	role:SetLevel(targetLevel);
	local level = role:GetLevel();
	if level ~= targetLevel then
		print( "InitRobot set level failed! target level="..targetLevel );
	end

