function EquipWeapon()
    local bag = TargetRole:GetItemBag();
	local item = bag:GetItem(CONSLOT_EQUIPPED, NES_MAIN_HAND);

	if not g_bInitRobotData then
		InitRobotData();
	end

	if item == nil then
		local itemTable = g_EquipmentTable[role:GetSex()][TargetRole:GetClass()][ITEMSUBTYPE_EQUIP_WEAPON];
		if itemTable then
			local itemCount = #(itemTable.item);
			if itemCount > 0 then
				local ret = -1;
				ret = bag:DeleteItemPos(CONSLOT_DEFAULT, 1, 1, ITEMLOG_GM_COMMAND);
				if ret ~= errSuccess then
					print("delete item failed when EquipWeapon, ret="..ret);
				end

				local itemTemplateID = itemTable.item[math.random(1, itemCount)];
				local equip_item = CItemMgr:GetInstance():GenerateItem(itemTemplateID, 1, 'robot.lua', 422);
				local ret = bag:AddItem(equip_item, ITEMLOG_GM_COMMAND, 0);
				if ret ~= errSuccess then
					print("add item "..itemTemplateID.. " failed when EquipWeapon, ret="..ret);
					CItemMgr:GetInstance():DestroyItem(equip_item, 'robot.lua', 426);
					return;
				end
				local item_pos = equip_item.m_iteminfo.m_byItemSlot;
				if equip_item.m_iteminfo.m_byIdentified == 0 then
					bag:IdentifyItem(CONSLOT_DEFAULT, item_pos);
				end
				ret = bag:MoveItem(CONSLOT_DEFAULT, item_pos, CONSLOT_EQUIPPED, itemTable.slot);
				if ret ~= errSuccess then
					print("move item failed when EquipWeapon, ret="..ret);
				end
			end
		end
	end
end
