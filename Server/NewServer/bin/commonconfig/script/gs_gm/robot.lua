			local itemCount = #(itemTable.item);
			if itemCount > 0 then
				local itemTemplateID = itemTable.item[math.random(1, itemCount)];
                local equip_item = CItemMgr:GetInstance():GenerateItem(itemTemplateID, 1, 'robot.lua', 272);
