	                bag:IdentifyItem(CONSLOT_DEFAULT, item_pos);
				end
                bag:MoveItem(CONSLOT_DEFAULT, item_pos, CONSLOT_EQUIPPED, itemTable.slot);

				if i == ITEMSUBTYPE_EQUIP_RING then
					local itemTemplateID = itemTable.item[math.random(1, itemCount)];
					local equip_item = CItemMgr:GetInstance():GenerateItem(itemTemplateID, 1, 'robot.lua', 282);
					bag:AddItem(equip_item, ITEMLOG_GM_COMMAND, 0);
					local item_pos = equip_item.m_iteminfo.m_byItemSlot;
					if equip_item.m_iteminfo.m_byIdentified == 0 then
