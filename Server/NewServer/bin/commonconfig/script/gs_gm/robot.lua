    role:GetItemBag():SetMoney(MONEYTYPE_02, math.random(1, 100000000));
    role:GetItemBag():AddMoney(MONEYTYPE_SOUL_PTS, math.random(1, 1000000000), MONEYLOG_GM_COMMAND, 0, 0);
    role:GetItemBag():AddMoney(MONEYTYPE_SPELL_PTS, math.random(1, 1000000000), MONEYLOG_GM_COMMAND, 0, 0);
	role:GetSpirit():SetLevel(math.random(30, MAX_SPIRIT_LEVEL));
	role:SubscribeVIP(3, 1);

	if not g_bInitRobotData then
		InitRobotData();
	end

--------------------------------------------------------------------------------
-- refine
	for i = NES_MAIN_HAND, NES_TOTAL - 1 do
		if i ~= NES_AVATAR then
			role:GetItemBag():SetRefineLevel(i, math.random(1, 120));
		end
	end

--------------------------------------------------------------------------------
-- blood
    for i = 0, MAX_BLOODSEA_PAGE - 1 do
        role:GetSpirit():OpenBlood(i);
        for j = 0, MAX_BLOODSEA_SLOT_PER_PAGE - 1 do
            role:GetSpirit():SetBlood(i, j, math.random(1, MAX_BLOODSEA_SLOT_NUMBER));
        end
    end

--------------------------------------------------------------------------------
-- equipment

	--SetLevel(LVRequest);
	role:GetAttrList():AddAttrA(TargetRole, catMaxPhyAtk, 100);
	role:GetAttrList():AddAttrA(TargetRole, catMaxMagAtk, 100);
	role:GetAttrList():AddAttrA(TargetRole, catMaxTaoAtk, 100);
