g_bInitRobotData = false;

function tryFillEquipTable(class, data)
	if data.m_byRequireGender < cstInvalid or data.m_byRequireGender >= cstAsexual  then
		print("wrong data.m_byRequireGender "..data.m_byRequireGender.." for equipment "..data.m_nTemplateID);
		return false;
	end
	
	local AllClass = (2^clsWarrior) + (2^clsMage) + (2^clsRogue) + (2^clsArcher) + (2^clsTaoist);
	if data.m_byRequireClass == (2^class) or data.m_byRequireClass == AllClass then
		if data.m_byRequireGender == cstInvalid then
			if g_EquipmentTable[cstMale][class][data.m_bySubType] then
				table.insert(g_EquipmentTable[cstMale][class][data.m_bySubType].item, data.m_nTemplateID);
			end	
			if g_EquipmentTable[cstFemale][class][data.m_bySubType] then
				table.insert(g_EquipmentTable[cstFemale][class][data.m_bySubType].item, data.m_nTemplateID);
			end									
		else
			if g_EquipmentTable[data.m_byRequireGender][class][data.m_bySubType] then
				table.insert(g_EquipmentTable[data.m_byRequireGender][class][data.m_bySubType].item, data.m_nTemplateID);
			end
		end
	end
	return true;
end

function InitRobotData()
--------------------------------------------------------------------------------
-- equipment
	local AllClass = (2^clsWarrior) + (2^clsMage) + (2^clsRogue) + (2^clsArcher) + (2^clsTaoist);
	local data = CDataManager_EQUIP_DATA_:GetInstance():GetFirstData();
	while data do
		if (data.m_byType == ITEMTYPE_EQUIP and data.m_nTemplateID > 0 ) then

			if data.m_byRequireClass == (2^clsWarrior) or data.m_byRequireClass == AllClass then
				tryFillEquipTable(clsWarrior,data);
			end
			if data.m_byRequireClass == (2^clsMage) or data.m_byRequireClass == AllClass then
				tryFillEquipTable(clsMage,data);
			end
			if data.m_byRequireClass == (2^clsRogue) or data.m_byRequireClass == AllClass then
				tryFillEquipTable(clsRogue,data);
			end
			if data.m_byRequireClass == (2^clsArcher) or data.m_byRequireClass == AllClass then
				tryFillEquipTable(clsArcher,data);
			end
			if data.m_byRequireClass == (2^clsTaoist) or data.m_byRequireClass == AllClass then
				tryFillEquipTable(clsTaoist,data);
			end
		end

		data = CDataManager_EQUIP_DATA_:GetInstance():GetNextData();
	end

--------------------------------------------------------------------------------
-- air



	g_bInitRobotData = true;
end

function InitRobot(bRandItem)
