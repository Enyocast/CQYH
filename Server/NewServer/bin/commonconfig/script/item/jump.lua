function _get_jump_point(pRole, nSceneTempID, nRandNumber)
	local t = JUMP_TABLE[nSceneTempID];

	if not t then
		return 0, 0, 0;
	elseif t.sub_district then
		local tt = t;
		t = nil;
		for i, v in pairs(tt) do
			if type(v) == 'table' then
				local x = pRole:GetX();
				local y = pRole:GetY();
				local z = pRole:GetZ();
				if x >= v.lt.x and x <= v.rb.x and y >= v.lt.y and y <= v.rb.y and z >= v.lt.z and z <= v.rb.z then
					t = v.list;
					break;
				end
			end
		end
	end

	if not t then
		return 0, 0, 0;
	else
		local pos = (nRandNumber % (#t)) + 1;
		return t[pos].x, t[pos].y, t[pos].z;
	end
end

