function convert_rectangle(lt, rb)
	local p1 = { x = lt.x, y = lt.y, z = lt.z };
	local p2 = { x = lt.x, y = rb.y, z = lt.z };
	local p3 = { x = rb.x, y = rb.y, z = lt.z };
	local p4 = { x = rb.x, y = lt.y, z = lt.z };

	convert(p1);
	convert(p2);
	convert(p3);
	convert(p4);

	lt.x = p2.x;
	lt.y = p1.y;
	rb.x = p4.x;
	rb.y = p3.y;
end

